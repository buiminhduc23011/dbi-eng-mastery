    public static async Task SeedAsync(AppDbContext db)
    {
        await db.Database.MigrateAsync();

        // Add-missing (by Term): safe to re-run after adding new seed batches.
        var existingTerms = (await db.VocabCards.Select(c => c.Term).ToListAsync())
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        var allCards = GetCards()
            .Concat(GetExtraCards())
            .Concat(GetWorkCards())
            .Concat(GetCommunicationCards())
            .ToList();
        var missingCards = allCards.Where(c => !existingTerms.Contains(c.Term)).ToList();
        if (missingCards.Count > 0)
        {
            db.VocabCards.AddRange(missingCards);
            await db.SaveChangesAsync();
        }

        var existingDrills = (await db.SentenceDrills
            .Select(d => d.PromptVi + "\n" + d.TargetEn).ToListAsync())
            .ToHashSet(StringComparer.Ordinal);
        var allSeeds = GetDrillSeeds().Concat(GetExtraDrillSeeds()).ToList();
        var missingSeeds = allSeeds
            .Where(s => !existingDrills.Contains(s.PromptVi + "\n" + s.TargetEn)).ToList();
        if (missingSeeds.Count > 0)
        {
            foreach (var d in missingSeeds)
            {
                db.SentenceDrills.Add(new SentenceDrill
                {
                    Category = d.Category,
                    PromptVi = d.PromptVi,
                    TargetEn = d.TargetEn,
                    AlternativesEnJson = JsonSerializer.Serialize(d.Alts),
                    KeywordsJson = JsonSerializer.Serialize(d.Keywords),
                    GrammarNote = d.GrammarNote,
                    NextReviewDate = DateTime.UtcNow,
                });
            }
            await db.SaveChangesAsync();
        }

        var defaults = new Dictionary<string, string>
        {
            ["DailyTarget"] = "20",
            ["GeminiModel"] = "gemini-2.5-flash",
            ["GeminiApiKey"] = "",
        };
        foreach (var (k, v) in defaults)
            if (await db.AppSettings.FindAsync(k) is null)
                db.AppSettings.Add(new AppSetting { Key = k, Value = v });
        await db.SaveChangesAsync();
    }
